def relabellings(
    generator, instance, values: Sequence[str], width: int
) -> list[list[str]]:
    """Every filing this family's registered value maps can make of A's answers.

    Dispatched on the DECLARED profile, so a family whose answers are words is never
    priced by maps between two published vocabularies it does not have, and a family
    that has them is never priced by character maps that mean nothing to it.
    """
    profile = profile_of(generator)
    if profile == ORDERED_TOKENS:
        source = answer_ranks_for(generator, instance.a.table)
        target = answer_ranks_for(generator, instance.b.table)
        return token_relabellings(values, source or (), target or (), width)
    if profile == SOUNDCHANGE_V1:
        answer_ranks_for(generator, instance.a.table)
        answer_ranks_for(generator, instance.b.table)
        return character_relabellings(values, width)
    raise ValueError(f"no copy family is registered for profile {profile!r}")


