"""What "reusing A's answers on B" means for one family, and which family means which.

THE COPY SCREEN PRICES A FAMILY OF MAPS, and the family is a property of what a task
publishes rather than of the screen. Ledger publishes a complete ordered vocabulary of
whole row answers: the band table each sibling prints, in the order it prints it. The
cheapest transfer there is to read both tables off the two task texts and send first to
first, so the registered maps are dictionaries between two published orders, closed
under composition. Sound change publishes no such vocabulary. It publishes a phoneme
alphabet and a word grammar, and a whole daughter form is not a token of an ordered
list: returning the daughters B's drawn key realized would price a transfer nobody can
perform, because producing that list means already knowing what the draw did to B, and
enumerating every legal word up to sixteen phones is not a list either. Its registered
maps are global character maps instead: every permutation of the three deletable vowels
and every permutation of the three replacement phones, applied to A's correct daughters.

SO THE PROFILE IS DECLARED, NOT INFERRED. A generator declares `COPY_PROFILE` and
`registry.load_generator` refuses one that does not, because the failure a default
would produce is silent: a family whose answers are words, priced under the token
profile, reports the maximum of a family of maps that cannot be built, and the bar is
read against a number that measured nothing. A profile this module does not know is
refused for the same reason.

THE BAR AND THE FAMILY ARE ONE REGISTRATION. A screen that enumerates more maps reports
a larger maximum whether or not the extra maps are a real channel, so a number measured
against one family means nothing held against another. `soundchange_v1` and its 0.50
bar are a NEW registration under the gate label this build publishes; 0.50 is carried
over as a conservative initial ceiling and inherits none of the ordered-token profile's
empirical calibration.

BOTH FAMILIES ARE CLOSED under composition, which is why each is a family and not a
list. The row moves are generated by the rotation and the reversal, so their closure is
the dihedral group: every rotation of the sequence and of its reversal, 48 moves at 24
rows. The ordered-token maps are the registered dictionaries and every composition of
them, computed generically rather than listed. The character maps are the product of
two symmetric groups on disjoint letter sets, which is closed as it stands. Token and
character maps act on values and row moves on positions, so the two commute, and a
product of two commuting closed families is closed.
"""

from __future__ import annotations

import itertools
from typing import Iterable, Mapping, Sequence

#: The declared profiles. A generator names one of these and nothing else.
ORDERED_TOKENS = "ordered_tokens"
SOUNDCHANGE_V1 = "soundchange_v1"
PROFILES = (ORDERED_TOKENS, SOUNDCHANGE_V1)

#: Which profiles consume the family's published answer ranks. A profile that does not
#: is the reason `answer_ranks` may return None: an empty tuple would be a fictitious
#: complete vocabulary, and a screen built over it would report a maximum of nothing.
CONSUMES_RANKS = {ORDERED_TOKENS: True, SOUNDCHANGE_V1: False}

#: The letters the sound change character maps permute among themselves: the three
#: vowels the deletion pass can remove, and the three phones the replacement pass can
#: introduce. Every other character is fixed, so the map is a relabelling of exactly
#: the symbols whose identity the hidden rule chooses.
DELETABLE_VOWELS = ("a", "e", "i")
REPLACEMENT_PHONES = ("g", "x", "s")


def profile_of(generator) -> str:
    """The copy profile this generator declares, refused when it declares none.

    Refused rather than defaulted. A default is a decision about what a family's
    answers are, taken by whoever wrote this module about a family they have not seen.
    """
    declared = getattr(generator, "COPY_PROFILE", None)
    name = getattr(generator, "name", type(generator).__name__)
    if declared is None:
        raise ValueError(
            f"{name!r} declares no COPY_PROFILE. The copy screen prices a registered "
            f"family of maps and the bar is read against exactly that family, so a "
            f"generator says which one its answers are; the declared profiles are "
            f"{', '.join(PROFILES)}"
        )
    if declared not in PROFILES:
        raise ValueError(
            f"{name!r} declares copy profile {declared!r}; the registered profiles are "
            f"{', '.join(PROFILES)}"
        )
    return str(declared)


def require_profile(generator):
    """Refuse a generator that does not declare a registered profile. Returns it."""
    profile_of(generator)
    return generator


def answer_ranks_for(generator, table) -> tuple[str, ...] | None:
    """The family's published answer order, or None where the profile consumes none.

    A rank profile that returns None has no published vocabulary and cannot be priced
    by maps between two of them; a non-rank profile that returns a list has published
    one and should be priced by them. Either way the declaration and the callback
    disagree, which is refused here rather than turned into a smaller maximum.
    """
    profile = profile_of(generator)
    ranks = generator.answer_ranks(table)
    if CONSUMES_RANKS[profile]:
        if ranks is None:
            raise ValueError(
                f"{generator.name!r} declares the {profile!r} profile and publishes no "
                "answer ranks, so the transfer its bar is read against cannot be built"
            )
        return tuple(ranks)
    if ranks is not None:
        raise ValueError(
            f"{generator.name!r} declares the {profile!r} profile, which consumes no "
            "answer ranks, and returned some; a family that publishes a complete "
            "ordered vocabulary is priced by the maps between two of them"
        )
    return None


