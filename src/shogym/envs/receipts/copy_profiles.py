# the ordered-token profile
# --------------------------------------------------------------------------


def token_generators(
    values: Sequence[str],
    source_ranks: Sequence[str],
    target_ranks: Sequence[str],
) -> list[dict[str, str]]:
    """The registered token dictionaries themselves, before anything is closed.

    EVERY TARGET SIDE IS A PUBLISHED VOCABULARY. The RANK map takes the two tasks' own
    published answer orders and sends first to first: it is the cheapest transfer there
    is, because both orders are printed in the two task texts and reading them off
    needs no induction at all. Its rotations come with it. The LEXICAL map is the same
    construction over the published vocabularies sorted alphabetically, which is what a
    reader with no sense of the order would write. The FILED map narrows the source to
    the answers the agent actually filed on A, which it knows without inducing
    anything, and sends them into the same published target order.

    The target side is never the tokens B's drawn key happened to realize. A map into
    the realized target prices a transfer nobody could perform: producing it means
    already knowing what the hidden draw did to B, which is the thing the screen exists
    to bound. It is also not measuring the surface pair, since it moves with the draw,
    and the bar was read against the numbers it inflated.

    These are the GENERATORS. What the screen is read against is what they generate,
    which `token_maps` computes.
    """
    out: list[dict[str, str]] = []
    # AN EMPTY VALUE IS NOT AN ANSWER THE AGENT FILED. A reduced filing holds a value
    # at the rows the receipt reported and nothing at the rest, and the empty positions
    # are rows the reader has no token for. Counting the absence as a filed answer would
    # register a map that carries it into a published band, which credits the reader
    # with a value at a row it knows nothing about.
    filed = sorted(token for token in set(values) if token)
    for source, into in (
        (list(source_ranks), list(target_ranks)),
        (sorted(set(source_ranks)), sorted(set(target_ranks))),
        (filed, sorted(set(target_ranks))),
    ):
        if not source or not into:
            continue
        for shift in range(len(into)):
            out.append({s: into[(i + shift) % len(into)] for i, s in enumerate(source)})
    return out


def token_maps(
    values: Sequence[str],
    source_ranks: Sequence[str],
    target_ranks: Sequence[str],
) -> list[dict[str, str]]:
    """The registered token dictionaries CLOSED under composition, identity first.

    A LIST OF DICTIONARIES IS NOT THE FAMILY, and the difference has a price. Each
    registered dictionary is applied by leaving anything outside it alone, so it is a
    total function on the finite set of tokens the dictionaries and the filing mention,
    and two of them compose into a third total function on that same set. A rank map
    that carries A's bands into B's while leaving an untouched token alone, followed by
    a filed map that carries that token onward while leaving the already translated
    bands alone, is a map an agent builds from the same two published dictionaries and
    no more. Listing the dictionaries and not their compositions left such a map out,
    and on a real draw it scored 13 of 24 where the reported maximum was 11 of 24, so
    the bar admitted it.

    So this closes them, generically rather than by hand. Compositions are taken until
    no new map appears, which terminates because there are finitely many functions from
    a finite token set to itself. The result is a monoid: the identity is in it, and it
    is closed, so nothing an agent can build by chaining registered dictionaries is
    outside what the screen prices.
    """
    # AN EMPTY VALUE IS NOT A TOKEN ANY PUBLISHED VOCABULARY CARRIES, so no registered
    # map moves it and it is not in the set the maps are closed over. A filing that
    # holds nothing at a row is a row the reader has no token for; putting that absence
    # in the universe would price maps that carry it into a band, which is a map nobody
    # can build from two printed lists, and it would close the family over a point the
    # generators only ever map out of. The reduced-receipt diagnostic files exactly such
    # a filing, and with the absence in the universe its closure runs to tens of
    # thousands of maps on a family whose two vocabularies are the same six tokens.
    universe = sorted(token for token in
                      set(values) | set(source_ranks) | set(target_ranks) if token)
    if not universe:
        return [{}]
    position = {token: n for n, token in enumerate(universe)}

    def total(table: Mapping[str, str]) -> tuple[str, ...]:
        """One dictionary as its images over the whole token set, in one order."""
        return tuple(table.get(token, token) for token in universe)

    def after(first: tuple[str, ...], second: tuple[str, ...]) -> tuple[str, ...]:
        """`first` and then `second`, which is a map on the same token set."""
        return tuple(second[position[image]] for image in first)

    identity = tuple(universe)
    found = [identity]
    known = {identity}
    for table in token_generators(values, source_ranks, target_ranks):
        made = total(table)
        if made not in known:
            known.add(made)
            found.append(made)
    frontier = list(found)
    while frontier:
        fresh: list[tuple[str, ...]] = []
        against = list(found)
        for one in frontier:
            for other in against:
                for made in (after(one, other), after(other, one)):
                    if made not in known:
                        known.add(made)
                        found.append(made)
                        fresh.append(made)
        frontier = fresh
    return [dict(zip(universe, image)) for image in found]


def token_relabellings(
    values: Sequence[str],
    source_ranks: Sequence[str],
    target_ranks: Sequence[str],
    width: int,
) -> list[list[str]]:
    """Every filing the closed token family can make of A's answers, deduplicated.

    The identity is among the maps, so the untouched filing leads the list and
    composing this with the row moves produces those moves themselves.

    THE ORBIT OF THE FILING, NOT THE MONOID OF MAPS, and the two give the same set. A
    composition applied to a filing is the first dictionary applied to it and then the
    next, so closing the FILINGS under the registered dictionaries reaches exactly what
    closing the dictionaries first and applying each would. What it does not do is build
    the monoid: where two published vocabularies are the same six tokens and one
    registered dictionary is not injective, that monoid runs to tens of thousands of
    maps which between them make a few dozen filings, and closing it took a quarter of
    an hour on one reduced filing. `token_maps` remains the statement of what the family
    IS, and this is the family as it reaches a filing.
    """
    generators = token_generators(values, source_ranks, target_ranks)
    start = list(values)
    reached: dict[tuple[str, ...], list[str]] = {tuple(start): start}
    frontier = [start]
    while frontier:
        fresh: list[list[str]] = []
        for filing in frontier:
            for table in generators:
                made = [table.get(value, value) for value in filing]
                if tuple(made) not in reached:
                    reached[tuple(made)] = made
                    fresh.append(made)
        frontier = fresh
    seen: dict[tuple[str, ...], list[str]] = {}
    for filing in reached.values():
        fitted = fit(filing, width)
        seen.setdefault(tuple(fitted), fitted)
    return list(seen.values())


