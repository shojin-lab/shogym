def character_maps() -> list[dict[str, str]]:
    """The registered global character maps: 36, identity first.

    Every permutation of the three deletable vowels crossed with every permutation of
    the three replacement phones, every other character fixed. The two letter sets are
    disjoint, so the product is the direct product of two symmetric groups and is
    closed under composition as it stands.

    WHY THESE LETTERS. They are the symbols the hidden rule names. A reader holding A's
    corrected key can see which phone replaced k and which vowel went missing, and the
    cheap thing to try on B is the same daughter with those identities swapped for the
    ones it guesses. A wider family of arbitrary character bijections would price maps
    that turn one form's inert consonants into another's, which is what the analogy
    check prices separately and by its own construction rather than by relabelling.
    """
    out: list[dict[str, str]] = []
    for vowels in itertools.permutations(DELETABLE_VOWELS):
        for phones in itertools.permutations(REPLACEMENT_PHONES):
            table: dict[str, str] = dict(zip(DELETABLE_VOWELS, vowels))
            table.update(zip(REPLACEMENT_PHONES, phones))
            out.append(table)
    return out


def apply_characters(table: Mapping[str, str], value: str) -> str:
    """One character map applied to one whole value, character by character."""
    return "".join(table.get(character, character) for character in value)


def character_relabellings(values: Sequence[str], width: int) -> list[list[str]]:
    """Every filing the closed character family can make of A's answers, deduplicated.

    The identity map leads, so the untouched filing leads the list and composing this
    with the row moves produces those moves themselves.
    """
    seen: dict[tuple[str, ...], list[str]] = {}
    for table in character_maps():
        filing = fit([apply_characters(table, value) for value in values], width)
        seen.setdefault(tuple(filing), filing)
    return list(seen.values())


