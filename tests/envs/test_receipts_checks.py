def test_the_two_copy_thresholds_bind_independently() -> None:
    instance = _instance()
    assert checks.check_copy(GENERATOR, instance, 0.6, 0.95, 0.05).passed
    tight_copy = checks.check_copy(GENERATOR, instance, 0.01, 0.95, 0.05)
    assert not tight_copy.passed and "reusing A's answers" in tight_copy.detail
