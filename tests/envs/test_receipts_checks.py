def test_the_bars_are_registered_and_overridable() -> None:
    """They have values because someone chose them against a measured distribution.

    A bank record carries no bars at all; the bundle stores the registered set and
    refuses to verify against any other, so an override is diagnostic and leaves
    nothing durable behind it."""
    registered = admission.Thresholds()
    assert registered.registered
    assert registered.min_headroom == admission.REGISTERED_MIN_HEADROOM == 0.05
    assert registered.max_copy_score == admission.REGISTERED_MAX_COPY_SCORE == 0.50
    assert registered.max_flip_score == admission.REGISTERED_MAX_FLIP_SCORE == 0.875
    assert registered.min_leverage == admission.REGISTERED_MIN_LEVERAGE == 0.10
    assert not admission.Thresholds(max_copy_score=0.9).registered
    with pytest.raises(ValueError):
        admission.Thresholds(max_copy_score=float("nan"))


# ----- the registered bars, against the ledger's own distribution -----


def test_the_registered_bars_fill_a_bank() -> None:
    """The structural facts the bars were chosen against, checked on a small bank.

    The ledger's one-axis-wrong score is never below five sixths, so a flip bar under
    that admits nothing and 0.875 keeps the draws that are not the worst. Its weakest
    axis leverage never exceeds one sixth, so a leverage bar above that admits nothing
    and 0.10 sits under the ceiling. Together the bars have to leave enough supply to
    fill a bank, and that is what this asserts rather than any particular yield.
    """
    from shogym.envs.receipts import bank as bank_mod

    registered = admission.Thresholds()
    built = bank_mod.materialize(GENERATOR, MASTER, 4)
    found = bank_mod.population(built, GENERATOR)
    assert built.size == 4
    assert len(found.instances) == 4
    assert found.considered >= 4
    assert registered.max_flip_score == 0.875
    assert registered.min_leverage == 0.10


def test_every_admitted_instance_clears_every_registered_bar() -> None:
    registered = admission.Thresholds()
    admitted = 0
    for ordinal in range(12):
        instance = draw(GENERATOR, MASTER, ordinal)
        report = admission.report(GENERATOR, instance, MASTER, registered)
        if not report.admitted:
            continue
        admitted += 1
        assert report.gates.headroom > registered.min_headroom
        scores = checks.copy_scores(GENERATOR, instance)
        plain = max(scores[name] for name in checks.NO_INDUCTION_MAPS)
        assert plain <= registered.max_copy_score
        assert scores["option_flip"] <= registered.max_flip_score
        assert min(checks.axis_leverage(GENERATOR, instance).values()) >= (
            registered.min_leverage
        )
    assert admitted, "the registered bars admitted nothing in twelve draws"


def test_the_bars_bite_where_the_distribution_says_they_do() -> None:
    """A flip bar below five sixths empties the sample; a leverage bar above one
    sixth does the same. Both are the structural facts the middle set sits between."""
    registered = admission.Thresholds()
    flips: list[float] = []
    leverages: list[float] = []
    for ordinal in range(8):
        instance = draw(GENERATOR, MASTER, ordinal)
        flips.append(checks.copy_scores(GENERATOR, instance)["option_flip"])
        leverages.append(min(checks.axis_leverage(GENERATOR, instance).values()))
    # The component score is rounded to six places, which is registered, so five
    # sixths appears as 0.833333 and the comparison is made at that rounding.
    assert min(flips) >= round(5 / 6, 6)
    assert max(leverages) <= round(1 / 6, 6)
    assert registered.max_flip_score > 5 / 6
    assert registered.min_leverage < 1 / 6


def test_a_bank_is_filled_under_the_registered_bars_or_not_at_all() -> None:
    """A caller's loosened bars are refused, not honoured.

    `settled` is the gate set's own constants, R's arity and blocks and H's headroom.
    The named checks' bars are outside it, so a set that moved copy, flip and leverage
    is settled and not registered, and a bank could once be filled under it. Every bar
    is what admitted the instances, so every bar is what a bank is filled under.
    """
    from shogym.envs.receipts import bank as bank_mod

    loose = admission.Thresholds(max_copy_score=0.9, max_flip_score=0.99,
                                 min_leverage=0.01)
    assert loose.settled and not loose.registered
    # And a moved H bar is not settled either: H is part of what the gate name means.
    assert not admission.Thresholds(min_headroom=0.0).settled
    built = bank_mod.materialize(GENERATOR, MASTER, 1)
    with pytest.raises(ValueError, match="only the registered bars may fill a bank"):
        bank_mod.population(built, GENERATOR, loose)
    # The population is a function of the registered rule, not of a caller's bars.
    assert bank_mod.population(built, GENERATOR).ordinals == bank_mod.population(
        built, GENERATOR, admission.Thresholds()
    ).ordinals


def test_the_admission_report_carries_the_bars_it_judged_against() -> None:
    instance = draw(GENERATOR, MASTER, 0)
    registered = admission.report(GENERATOR, instance, MASTER, admission.Thresholds())
    loose = admission.report(
        GENERATOR, instance, MASTER, admission.Thresholds(max_copy_score=0.9)
    )
    assert registered.thresholds.registered
    assert registered.digest() != loose.digest()
