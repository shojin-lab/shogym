"""The named checks, and what each one is for.

Each check is named separately from the gates because failing it means something
different, so each is exercised on the ledger and, where a failure can be
constructed, on something that fails it.
"""

from __future__ import annotations

import pytest

from shogym.envs.receipts import admission, checks
from shogym.envs.receipts.generators.ledger import GENERATOR
from shogym.envs.receipts.protocol import draw
from shogym.envs.receipts.registry import load_generator

MASTER = bytes(range(32))
# Diagnostic bars, not the registered ones: loose enough that the fixture instance
# clears them, so a test about something else does not fail on a threshold.
THRESHOLDS = admission.Thresholds(
    max_copy_score=0.6, max_flip_score=0.95, min_leverage=0.05
)


def _instance(ordinal: int = 0):
    return draw(GENERATOR, MASTER, ordinal)


