def test_every_relabel_target_is_a_published_vocabulary() -> None:
    """A map into what B's drawn key happened to realize prices induction.

    Producing that filing means already knowing what the hidden draw did to B, which
    is the thing the screen exists to bound. It also made the copy verdict a property
    of the draw rather than of the surface pair. Every target side is the published
    answer order, so the relabel best is reachable from the two task texts alone.
    """
    instance = _instance()
    published = set(GENERATOR.answer_ranks(instance.b.table))
    realized = set(instance.b.key)
    assert realized <= published
    for filing in checks.copy_map_filings(GENERATOR, instance)["relabel"]:
        assert set(filing) <= published | set(instance.a.key) | {""}


def test_the_registered_row_moves_are_closed_under_composition() -> None:
    """A LIST OF GENERATORS IS NOT THE FAMILY, and this asserts the difference.

    The registered row moves are generated by the rotation and the reversal. An
    enumeration that listed those two without their compositions left out every
    reversal followed by a rotation, and the containment and product-size checks below
    passed on it: they say the family holds its parts, not that it holds their
    compositions. This composes every pair of moves on unique row markers and requires
    the result to be a member.
    """
    markers = tuple(f"r{n:02d}" for n in range(24))
    moves = [tuple(move) for move in checks._permutations(list(markers), len(markers))]
    assert len(moves) == len(set(moves)) == 48  # the dihedral group on 24 positions

    # Each move as the positions it reads from, so it can be applied to any sequence.
    order = {move: tuple(markers.index(marker) for marker in move) for move in moves}

    def apply(move, sequence):
        return tuple(sequence[position] for position in order[move])

    members = set(moves)
    for first in moves:
        for second in moves:
            assert apply(second, apply(first, markers)) in members


def test_the_registered_token_maps_are_closed_under_composition() -> None:
    """The token factor, asserted the way the row factor is.

    Each registered dictionary is applied by leaving anything outside it alone, so it
    is a total function on the tokens the dictionaries and the filing mention, and two
    of them compose into a third. Listing the dictionaries and not their compositions
    left such a map out, and one of those scored 13 of 24 on a draw whose reported
    maximum was 11 of 24.
    """
    instance = _instance(7)
    values = list(instance.a.key)
    source_ranks = GENERATOR.answer_ranks(instance.a.table)
    target_ranks = GENERATOR.answer_ranks(instance.b.table)
    maps = checks._token_maps(values, source_ranks, target_ranks)
    universe = sorted(set(values) | set(source_ranks) | set(target_ranks))

    def total(table):
        return tuple(table.get(token, token) for token in universe)

    members = {total(table) for table in maps}
    assert len(members) == len(maps)  # no member is listed twice
    assert tuple(universe) in members  # the identity is one of them

    position = {token: n for n, token in enumerate(universe)}
    for first in members:
        for second in members:
            composed = tuple(second[position[image]] for image in first)
            assert composed in members

    # And closing again finds nothing, so what the screen prices is a fixed point.
    again = checks._token_maps(values, source_ranks, target_ranks)
    assert {total(table) for table in again} == members


def test_the_whole_registered_copy_family_is_closed() -> None:
    """ONE PROPERTY OVER THE WHOLE FAMILY, so an unclosed addition fails loudly.

    Three times a registered family was enumerated from its generators rather than
    closed: first the row moves without their compositions, then the token maps
    without theirs. Product size and sub-family containment pass on both, because they
    say the family holds its parts and not their compositions. This says the thing
    that was false: applying any registered transformation to any registered filing
    lands on a registered filing.

    It runs on a small vocabulary rather than a ledger draw so the whole product can
    be walked exhaustively. What it checks is the construction, which does not know
    how many rows or bands a family has.
    """
    values = ["low", "mid", "high", "low", "mid", "high"]
    source_ranks = ["low", "mid", "high"]
    target_ranks = ["one", "two", "three"]
    width = len(values)

    token_maps = checks._token_maps(values, source_ranks, target_ranks)
    relabels = checks._relabellings(values, source_ranks, target_ranks, width)
    family = checks._distinct(
        filing
        for relabelled in relabels
        for filing in checks._permutations(relabelled, width)
    )
    members = {tuple(filing) for filing in family}
    assert len(members) == len(family) > len(relabels)

    # Every registered transformation, as it is actually applied: a token map on the
    # values, and a row move on the positions.
    markers = [f"p{n}" for n in range(width)]
    orders = [
        tuple(markers.index(marker) for marker in move)
        for move in checks._permutations(markers, width)
    ]
    for filing in family:
        for table in token_maps:
            relabelled = [table.get(value, value) for value in filing]
            for order in orders:
                moved = tuple(relabelled[position] for position in order)
                assert moved in members


def test_the_registered_copy_family_is_closed_under_composition() -> None:
    """The bar is read against a family, and this one is closed.

    Relabelling A's answers and permuting the rows are the two registered moves. They
    act on different things, so they commute and composing them in either order
    generates nothing further; enumerating each alone reported a maximum no map in the
    family could reach. The three named maps are sub-families of the closure and are
    printed for diagnosis, so a failure says which cheap map did it.
    """
    instance = _instance()
    filings = checks.copy_map_filings(GENERATOR, instance)
    # Exhaustive: every relabelling under every permutation, and nothing dropped.
    assert len(filings["closure"]) == len(filings["relabel"]) * len(
        filings["permutation"]
    )
    for name in checks.REPORTED_MAPS:
        assert all(filing in filings["closure"] for filing in filings[name]), name
    scores = checks.copy_scores(GENERATOR, instance)
    assert scores["closure"] >= max(scores[name] for name in checks.REPORTED_MAPS)
    assert "closure" in checks.NO_INDUCTION_MAPS
    assert "option_flip" not in checks.NO_INDUCTION_MAPS
    result = checks.check_copy(
        GENERATOR, instance, admission.REGISTERED_MAX_COPY_SCORE, 0.875, 0.1
    )
    assert "over the closed family" in result.detail
    assert "alone: identity" in result.detail


def test_a_draw_a_composed_token_map_copies_is_excluded() -> None:
    """The draw the unclosed token family admitted, kept as the regression.

    Its rank map carries A's bands into B's and leaves an untouched token alone; its
    filed map carries that token onward and leaves the already translated bands alone.
    Both are registered dictionaries, and their composition, reversed and rotated, is
    a filing an agent builds from A's answers and B's published vocabulary alone. It
    earns 13 of 24, where the enumeration that listed the dictionaries and not their
    compositions reported 11 of 24 and the bar admitted it.
    """
    instance = _instance(7)
    scores = checks.copy_scores(GENERATOR, instance)
    assert scores["closure"] == round(13 / 24, 6)
    assert max(scores[name] for name in checks.REPORTED_MAPS) <= 0.5
    report = admission.report(GENERATOR, instance, MASTER, admission.Thresholds())
    assert report.gates.verdict  # the copy screen excludes it, not a gate
    assert report.failed_checks == ("copy",)
    assert not report.admitted


def test_a_draw_a_composed_row_move_copies_is_excluded() -> None:
    """The draw the incomplete enumeration admitted, kept as the regression.

    Its relabel alone earns 0.3333 and every listed row move alone earns nothing, so
    an enumeration without the compositions reported 0.5000 and the bar admitted it.
    A reversal followed by a rotation of the same relabel earns 0.5417, which is over
    the bar, and it is built from A's answers and B's published rows alone.
    """
    instance = _instance(43)
    scores = checks.copy_scores(GENERATOR, instance)
    assert scores["closure"] == round(13 / 24, 6)
    assert max(scores[name] for name in checks.REPORTED_MAPS) <= 0.5
    report = admission.report(GENERATOR, instance, MASTER, admission.Thresholds())
    assert report.gates.verdict  # it is the copy screen that excludes it, not a gate
    assert report.failed_checks == ("copy",)
    assert not report.admitted


def test_the_copy_bar_is_read_against_the_closure_and_not_a_sub_family() -> None:
    """A bar and the maps it is a maximum over are one registration.

    This instance's relabel alone is under the registered bar and its closure is over
    it, so a screen that stopped at the sub-families would admit an instance a cheap
    composed map copies.
    """
    instance = _instance()
    scores = checks.copy_scores(GENERATOR, instance)
    bar = admission.REGISTERED_MAX_COPY_SCORE
    assert max(scores[name] for name in checks.REPORTED_MAPS) <= bar < scores["closure"]
    failed = checks.check_copy(GENERATOR, instance, bar, 0.875, 0.1)
    assert not failed.passed
    assert "through closure" in failed.detail


